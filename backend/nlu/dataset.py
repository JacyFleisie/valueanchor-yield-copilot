# Bumped whenever the corpus changes shape, so the on-disk model cache in
# ``engine.py`` is rebuilt rather than reused against stale training data.
CORPUS_VERSION = 2

PERCENT_EXAMPLES = ("ten", "fifteen", "twenty", "five", "thirty", "twenty five", "twelve")


def _slot_values(lexicon: Any) -> dict[str, list[str]]:
    # Imported lazily: the glossary is the single source of truth for the words
    # this product can explain, and a module-level import would tie the dataset
    # to the retrieval layer for no benefit.
    from .knowledge import GLOSSARY

    items = lexicon.item_names or ["the item"]
    return {
        "item": items,
        "item2": list(reversed(items)) or ["the other item"],
        "noun": [lexicon.noun],
        "business": [lexicon.business_name],
        "sector": [lexicon.sector_name],
        "percent": list(PERCENT_EXAMPLES),
        "term": list(GLOSSARY),
    }


def _expand(template: str, slots: dict[str, list[str]], limit: int = 3) -> list[str]:
    """Fill a template's slots, cycling through values up to ``limit`` variants."""
    filled = [template]
    for index, (name, values) in enumerate(slots.items()):
        if "{" + name + "}" not in template or not values:
            continue
        expanded: list[str] = []
        for sentence in filled:
            if "{" + name + "}" not in sentence:
                expanded.append(sentence)
                continue
            for offset in range(min(limit, len(values))):
                value = values[(offset + index) % len(values)]
                expanded.append(sentence.replace("{" + name + "}", value, 1))
        filled = expanded
    return [re.sub(r"\{[a-z0-9]+\}", "", sentence).strip() for sentence in filled]


def build_training_data(lexicon: Any, holdout_ratio: float = 0.2, seed: int = 7) -> dict[str, Any]:
    """Return train/hold-out splits, expanded with the active sector's vocabulary.

    The split happens on templates, so hold-out sentences are phrasings the
    classifier has never been trained on.
    """
    rng = random.Random(seed)
    slots = _slot_values(lexicon)
    train_texts: list[str] = []
    train_labels: list[str] = []
    test_texts: list[str] = []
    test_labels: list[str] = []
    per_intent: dict[str, int] = {}

    for intent, _label, _description in INTENTS:
        # Both layers are trained on: the tidy hand-written set and the messy
        # real-world set, so the model is not only fluent in scripted English.
        templates = list(TEMPLATES[intent]) + list(EXTRA_TEMPLATES.get(intent, []))
        rng.shuffle(templates)
        # A ratio of zero means "keep everything for training", which the engine
        # uses for the model it actually ships after evaluation is done.
        cut = max(1, int(round(len(templates) * holdout_ratio))) if holdout_ratio > 0 else 0
        held = templates[:cut]
        trained = templates[cut:] or templates
        for sentence in _expand_phrases(trained, slots):
            train_texts.append(sentence)
            train_labels.append(intent)
        for sentence in _expand_phrases(held, slots):
            test_texts.append(sentence)
            test_labels.append(intent)
        per_intent[intent] = len(trained) + len(held)

    return {
        "train": (train_texts, train_labels),
        "test": (test_texts, test_labels),
        "templatesPerIntent": per_intent,
        "trainRows": len(train_texts),
        "testRows": len(test_texts),
    }


def _expand_phrases(templates: list[str], slots: dict[str, list[str]]) -> list[str]:
    rows: list[str] = []
    for template in templates:
        rows.extend(_expand(template, slots))
    return list(dict.fromkeys(rows))
